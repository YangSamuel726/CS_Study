// [매크로]
// 매크로는 전처리 단계에서 특정 이름이나 함수 형태의 사용을 미리 정의한 코드로 치환하는 규칙이다.
// 선행처리를 통해 코드의 매크로 부분은 매크로 몸체로 치환된다.

#define MACRO(x) ((x)*(x))
void Example()
{
    int i = MACRO(5); // 선행처리를 통해 전처리 단계에서 int i = ((5)*(5)); 로 치환됨
}

// 장점은 똑같은 함수보다 실행이 빠르다는 것이다.
// 단점은 선언이 복잡하고, 디버깅이 어렵다는 것이다. 그리고 추가적으로 치환이기 때문에 괄호를 많이 사용해야 한다.

// [인라인]
// 매크로 함수의 단점을 제거하면서 장점을 유지하려는 요구사항을 만족하는 함수이다.
inline int SQUARE(int x)
{
    return x * x;
}
// 인라인 함수는 컴파일러에 의해서 처리가 된다. 따라서 컴파일러가 성능에 해가 된다고 판단하면 inline 키워드를 무시하기도 하며
// 필요한 경우 일부 함수를 임의로 인라인 처리하기도 한다.

// 매크로와 달리 자료형을 정해야 하지만 template을 통해 일반화를 제공한다.
template <typename T>
inline T SQUARE(T x)
{
    return x*x;
}


