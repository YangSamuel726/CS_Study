// [C에서 제공하는 표준 입출력 스트림]
// C에서는 표준 입출력 대상과 프로그램을 연결지어주는 스트림을 자동 생성해준다. 또 stdio 라이브러리를 통해 표준 스트림을 사용하거나 추가 스트림을 열고 닫을 수 있도록 기능을 제공해준다.

// 기본적으로 따로 설정하지 않았다면 표준 입출력 대상은 키보드와 모니터이다.
// stdin - 표준 입력 스트림 - 키보드 대상으로 입력
// stdout - 표준 출력 스트림 - 모니터 대상으로 출력
// stderr - 표준 에러 스트림 - 모니터 대상으로 출력

// [stdio.h]
// c에서 기본 제공되어지는 stdio 라이브러리의 헤더파일로, 스트림 연결/해제 및 스트림을 통한 입출력을 지원한다.

// [문자 단위 입출력 함수]
// stdio(Standard Input/Output)헤더 파일이 제공하는 문자 출력 함수는 다음과 같다.
int putchar(int c);
int fputc(int c, FILE * stream);
// `putchar`함수는 인자로 전달된 문자 정보를 표준 출력 스트림으로 전송하는 함수이다.
// 반면에 `fputc`함수는 문자를 전송할 스트림을 지정할 수 있다.

// 문자 입력 함수는 다음과 같다.
int getchar(void);
int fgetc(FILE * stream);
// `getchar`함수는 표준 입력 스트림으로부터 하나의 문자를 입력 받아서 반환하는 함수이다.
// `fgetc`함수도 문자를 입력 받지만 문자를 입력 받을 스트림을 지정할 수 있다.

void IOTest(void)
{
    int ch1, ch2;

    ch1 = getchar();
    ch2 = fgetc(stdin);

    putchar(ch1);
    fputc(ch2, stdout);
}
// enter키 또한 입력이다.

// [문자 입출력에서의 EOF]
// EOF는 End Of File의 약자로서, 파일의 끝을 표현하기 위해서 정의해 놓은 상수이다.
// 따라서 파일을 대상으로 fgetc 함수가 호출되면, 그리고 그 결과로 EOF가 반환되면, 이는 '파일의 끝에 도달해서 더 이상 읽을 내용이 없다'는 뜻이 된다.

// 함수호출의 실패가 일어나거나 특정 키가 입력되는 경우 반환되어진다.
// Window : CTRL + Z / Linux : CTRL + D
void EOFTest(void)
{
    int ch;

    while(1)
    {
        ch=getchar();
        if(ch==EOF) break;
        putchar(ch);
    }
}


// [문자열 단위 입출력 함수]
int puts(const char * s);
int fputs(const char * s, FILE * stream);
// 마찬가지로 stream 인자를 통해 출력의 대상을 결정할 수 있다.
// puts를 통해 출력을 하면 자동으로 개행이 이뤄지지만, fputs로 출력을 하면 자동으로 개행이 이루어지지 않는다.

char * gets(char * s);
char * fgets(char * s, int n, FILE * stream);
