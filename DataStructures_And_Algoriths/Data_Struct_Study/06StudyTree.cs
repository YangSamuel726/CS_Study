// [Tree란?]
// 노드들이 부모와 자식 관계로 연결된 계층적 자료구조이다. 하나의 노드가 루트 역할을 하고 나머지 노드가 그 자손이 되는 계층 구조를 가진다.
// 트리는 그래프의 한 종류이다.

// [특징]
// 루트 노드 : 트리의 가장 위쪽 노드
// 리프 노드 : 자식이 없는 노드
// 간선 : 노드 사이의 연결
// 높이 : 루트에서 리프까지의 가장 긴 경로의 길이
// 깊이 : 루트에서 특정 노드까지의 경로의 길이
// 서브트리 : 노드와 그 자손으로 이루어진 트리

// [규칙]
// 루트를 제외한 각 노드에는 부모가 정확히 하나 있어야 한다.
// 루트에서 모든 노드에 도달할 수 있어야 한다.
// 연결 관계에 순환이 없어야 한다.

// [트리의 유형]
// 이진 트리 : 각 노드가 최대 두 개의 자식을 가질 수 있는 트리
// 이진 탐색 트리(BST) : 각 노드의 왼쪽 서브트리에 있는 노드들은 그 노드보다 작은 값만 포함하며, 오른쪽 서브트리는 그 노드보다 큰 값만 포함하는 이진 트리
// AVL 트리 : 왼쪽과 오른쪽 서브트리의 높이 차이가 1을 초과하지 않는 자가 균형 이진 탐색 트리
// 레드-블랙 트리 : 루트에서의 경로가 다른 경로보다 두 배 길지 않도록 보장하는 균형 이진 탐색 트리
// 트라이 : 문자열 데이터 세트에서 키를 효율적으로 검색하는 데 사용되는 트리

