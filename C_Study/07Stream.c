void FGetsMethodTest(void)
{
    char str[7];
    int i;

    for(i=0; i<3; i++)
    {
        fgets(str, sizeof(str), stdin);
        printf("read %d: %s \n", i+1, str); // 임의 입력시 개행이 두번 이루어지는것을 확인할 수 있다.
    }
}


