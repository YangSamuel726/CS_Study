using System;
using Microsoft.VisualBasic;

// 작성자 : 양사무엘
// 작성일자 : 2026-11-03
// 공부 주제 : 데이터 형식
// 목표 : 데이터 형식의 정의와 이해

class CS004_DataType
{
    // [데이터 형식(Data Type)이란?]
    // 프로그램에서 어떤 종류의 값을 다루는지, 그 값에 허용되는 작업이 무엇인지를 정하는 분류이자 규칙이다.

    // 데이터 형식(자료형)에는 C#이 제공하는 기본 데이터 형식이 있다. 이는 크게 4가지로 나뉜다.
    // - 숫자 형식
    // - 문자열 형식
    // - 논리 형식
    // - 오브젝트 형식
    // 이 중 문자열과 오브젝트 형식만 참조 형식에 해당하고 나머지는 전부 값 형식에 해당한다.

    // [숫자 데이터 형식]
    // 숫자 데이터 형식은 다시 정수, 부동 소수, 소수 계열로 나뉜다.

    // <정수>
    void IntegerTypes() // 정수 계열(9개)
    {
        byte b;     // 1byte,    부호 없는 정수,      0 ~ 255
        sbyte sb;   // 1byte,    signed byte,        -128 ~ 127
        short s;    // 2byte,    short integer,      -32,768 ~ 32,767
        ushort us;  // 2byte,    unsigned short      0 ~ 65,535
        int i;      // 4byte,    정수,               -2,147,483,648 ~ 2,147,483,647
        uint ui;    // 4byte,    unsigned int,       0 ~ 4,294,967,295
        long l;     // 8byte,    정수,               -922,337,203,685,477,508 ~ 922,337,203,685,477,507
        ulong ul;   // 8byte,    unsigned long,      0 ~ 18,446,744,073,709,551,615
        char c;     // 2byte,    유니코드 문자
    }
    // 상황에 맞는 데이터 형식을 사용하는 것이 중요하다. byte에 20억이 넘어가는 값을 담을 수 없고, 최대 50을 넘지 않는 수를 다루는데 long을 사용하는건 자원낭비이다.

    // 최대값을 넘어가거나 최솟값에서 내려갈경우 오버플로우나 언더플로우가 일어난다. 각 형식의 최대, 최소를 알고 플로우가 일어날 수 있는지를 인지하고 있어야 한다.

    // <부동 소수점>
    // 소수점을 이동시켜 수를 표현하기에 부동 소수점이라는 이름이 붙었다.
    // 정수가 표현못하는 소수를 표현할 수 있지만 단점도 있다.
    // - 소수점을 표현하는데 비트를 사용하기 때문에 일반적으로 같은 크기의 정수 계열 형식과 같은 크기의 수를 표현할 수 없다. 
    // - 산술 연산 과정이 정수 계열 형식보다 느리다.
    void FloatingPointType()
    {
        float f = 1543213.1415926535f;              // 4byte, 단일 정밀도 형식, 끝에 'f' 접미사를 붙여 표현
        double d = 3.14159265358979323846264338;    // 8byte, 복수 정밀도 형식
    }

    // <소수>
    void Decimal()
    {
        decimal d = 0.1235234685672984792835193875691908m; // 16byte, 끝에 'm' 접미사를 붙여 표현
    }


    // [문자 형식과 문자열 형식]
    // char 형식은 정수 형식이지만 문자 데이터도 다룬다.
    void CharString()
    {
        char c = 'c';           // 2byte, '' 작은 따옴표를 사용해서 표현
        string s = "string";    // 크기가 값에 따라 다름, "" 큰 따옴표를 사용해서 표현
    }


    // [논리 형식]
    // 참/거짓 두가지 정보만 있기에 1bit로도 표현할 수 있지만 컴퓨터가 기본적으로 다루는 데이터의 크기가 바이트 단위이기 때문에 1byte가 사용된다.
    void Boolean()
    {
        bool b = false; // 1byte
    }


    // [object 형식]
    // 박싱을 통해 값 형식을 참조 형식으로 다룰 수 있게 되었다. 또 언박싱으로 그 값을 꺼내올 수 있다. 다만 복사한 대상과 복사된 값은 서로 영향을 주지 않는다.
    // 박싱 언박싱 과정에서 객체 할당과 GC비용 유발, 타입 캐스팅 문제가 발생한다.
    void ObjectType()
    {
        object o = (short)67;
        char c = (char)(short)o;
        short s = (short)o;
        Console.WriteLine(c);
        Console.WriteLine(s);
    }


    // [상수와 열거 형식]
    // 상수는 값이 변하지 않는 변수로 const 키워드를 사용해 선언하며, 선언 이후에는 값을 바꿀 수 없다.
    const int CI = 5; // CI는 5라는 리터럴 값을 가지는 상수
    // 리터럴 : 소스 코드 상으로 명시된 특정 값

    // 열거 형식은 서로 관련된 이름 있는 상수들을 묶어 정의하는 값 형식이다.
    enum Alphabet
    {
        A,
        B,
        C
    }
    // 값을 명시하지 않으면 첫 상수부터 차례대로 0, 1, 2의 값을 할당해준다.


    // [Nullable]
    // 값이 없는 상태인 null을 허용하는 형식으로 '?'를 타입 뒤에 붙여 표시한다.
    int? nullInt;
    // 이는 다음 표현과도 같다.
    Nullable<int> nullInt2;


    // [var 데이터 형식]
    // C#은 강력한 형식의 언어이다. 그러나 var 키워드를 통해 약한 형식 검사를 하는 편리함도 지원한다.
    // int, string 같은 명시적 형식 대신 var를 사용하여 변수를 선언하면 컴파일러가 자동으로 해당 변수의 형식을 지정해준다.
    void VarType()
    {
        var a = 5;      // int 형식
        var s = "asdf"; // string 형식
    }


    // [Data Type과 System.Type]
    // Data Type, 즉 자료형은 위에서 충분히 설명했다. 그렇다면 System.Type은 도대체 무엇인가?
    // System.Type(이하 타입)은 자료형에 관한 정보를 조회하는 기능을 제공하는 추상 클래스이다.
    // 이를 통해 해당 자료형의 이름, 필드, 프로퍼티, 메서드, 상속 관계 등의 메타데이터에 접근 할 수 있다.
    // 리플렉션 또한 이를 바탕으로 가능하다.
    // GetType() 함수나 typeof() 키워드를 통해 자료형에 관한 정보를 메타데이터로부터 읽어와 타입 객체를 생성 및 받을 수 있다.

    static void Main()
    {
        CS004_DataType instance = new CS004_DataType();
        instance.ObjectType();
    }
}