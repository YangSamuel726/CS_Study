// 데이터의 입력과 출력은 프로그램의 흐름을 뜻하는 것이다. 프로그램을 중심으로 프로그램 안으로 데이터가 들어오는 것이 입력이고, 프로그램 밖으로 데이터가 흘러 나가는 것이 출력이다.
